-- Lo que quedó por verificar, seguido de una etapa a la siguiente (spec
-- seguimiento-de-pendientes-entre-etapas, pieza 1b de la reunión del 13/11/2026).
--
-- Cuando el candidato responde la evaluación, y después la prueba del puesto, un agente de IA
-- que NO califica revisa cada duda que dejó el CV (las afirmaciones declaradas y las que no
-- tenían información) y dice si quedó resuelta, si sigue pendiente o si empeoró, citando la
-- respuesta en que se basa. En la prueba revisa además lo que la evaluación dejó por verificar
-- (falta de evidencia, alertas y patrones del cuestionario). Quien entrevista recibe solo lo que
-- ninguna etapa pudo aclarar.
--
-- Ninguna nota cambia. Las filas que ya existen no se tocan: nadie tiene seguimiento al
-- desplegar, y se pide la primera vez que alguien abre su informe.

-- ============================================================================
-- 1 · El seguimiento de cada etapa de cada postulación
-- ============================================================================
-- Una fila por postulación y etapa, hecha como texto_informe (V84). «huella» resume los datos
-- con los que se hizo: si cambian (un CV recalificado, una respuesta nueva), la huella de los
-- datos de hoy ya no coincide y el informe vuelve a lo de siempre («Por contrastar») hasta que
-- llegue el seguimiento nuevo. «huella_pedida» es lo último que se pidió: el mismo pedido no se
-- paga dos veces.
CREATE TABLE seguimiento_pendiente (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id   bigint NOT NULL REFERENCES postulacion(id),
    etapa            text NOT NULL CHECK (etapa IN ('EVALUACION', 'PRUEBA')),
    huella           text,
    dudas            text,
    descartados      integer NOT NULL DEFAULT 0 CHECK (descartados >= 0),
    motivos          text,
    ejecucion_ia_id  bigint REFERENCES ejecucion_ia(id),
    huella_pedida    text,
    pedida_en        timestamptz,
    escrita_en       timestamptz,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT seguimiento_pendiente_una_por_etapa UNIQUE (postulacion_id, etapa)
);

COMMENT ON TABLE seguimiento_pendiente IS
    'Cómo quedó cada duda del CV (y, en la prueba, lo que dejó la evaluación) tras una etapa. '
    'No es una nota: solo vale mientras los datos de la etapa tengan la misma huella.';
COMMENT ON COLUMN seguimiento_pendiente.dudas IS
    'JSON: una entrada por duda seguida, con una COPIA de su texto, su clasificación y su pregunta '
    '(las afirmaciones del CV se borran al recalificarlo), el origen (CV o EVALUACION), el estado '
    '(RESUELTA, SIGUE_PENDIENTE o EMPEORO), el número de pregunta o el entregable, la cita y la '
    'explicación.';
COMMENT ON COLUMN seguimiento_pendiente.motivos IS
    'JSON: por qué se descartó cada respuesta del agente que no pasó la comprobación del código.';

