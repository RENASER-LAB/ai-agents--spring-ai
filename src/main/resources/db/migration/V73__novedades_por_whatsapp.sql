-- Novedades de la postulación por WhatsApp (12/10/2026). Ver specs/novedades-por-whatsapp.md
-- y docs/CONTRATO-NOVEDADES-POR-WHATSAPP.md.
--
-- Mientras espera, el portal le ofrece al candidato «Escribir por WhatsApp». Él escribe primero
-- al bot de RENASER desde el celular de su cuenta; el bot lo reconoce SOLO por el número y le
-- cuenta cómo va su proceso, y desde entonces le avisa cuando le toca hacer algo.
--
-- Esta migración prepara cinco cosas:
--
--   1. El celular de la cuenta, siempre en formato internacional (E.164).
--   2. El vínculo entre un número y una postulación, con su anuncio, su consentimiento y su
--      cierre.
--   3. La cola de avisos «te toca» hacia el bot, uno por transición y tipo.
--   4. Los números que se dieron de baja escribiendo «BAJA» al bot.
--   5. Los textos legales: el consentimiento WHATSAPP 1.0 y la versión 1.2 de PLATAFORMA.
--
-- Y el interruptor de la beta, apagado: se enciende el día que el número del bot pase a NUEVO.
--
-- ⚠️ Es la V73 porque la V72 la toma specs/umbral-del-perfil-integral.md, que va antes y
-- publica PLATAFORMA 1.1. La 1.2 de aquí lleva también su cambio.


-- ============================================================================
-- 1 · El celular de la cuenta, en E.164
-- ============================================================================
--
-- `persona.telefono` existe desde la V2 y nadie lo escribía: el teléfono que la IA lee del
-- currículum vive en `dato_cv`, es texto libre y no sirve para esto. Desde ahora lo pide el
-- registro y se guarda siempre como «+51987654321».
--
-- Sigue admitiendo nulo: las cuentas anteriores no lo tienen, y el borrado de datos lo vacía.
-- Si algún valor suelto se coló a mano, el de nueve cifras peruano se normaliza y el resto se
-- vacía; un CHECK que no se cumple en una fila tumbaría cualquier UPDATE posterior de esa
-- persona, aunque tocara otra columna.

UPDATE persona
   SET telefono = '+51' || regexp_replace(telefono, '[^0-9]', '', 'g')
 WHERE telefono IS NOT NULL
   AND telefono !~ '^\+'
   AND regexp_replace(telefono, '[^0-9]', '', 'g') ~ '^9[0-9]{8}$';

UPDATE persona
   SET telefono = NULL
 WHERE telefono IS NOT NULL
   AND telefono !~ '^\+[1-9][0-9]{7,14}$';

ALTER TABLE persona
    ADD CONSTRAINT persona_telefono_e164_check
        CHECK (telefono IS NULL OR telefono ~ '^\+[1-9][0-9]{7,14}$');

COMMENT ON COLUMN persona.telefono IS
    'El celular de la cuenta en E.164 («+51987654321»). Lo pide el registro desde la V73 y se '
    'cambia en «Mi cuenta». Nulo en las cuentas anteriores y tras el borrado de datos.';


-- ============================================================================
-- 2 · El vínculo de un número con una postulación
-- ============================================================================
--
-- Una fila por cada vez que el candidato pulsa «Escribir por WhatsApp» en una postulación que
-- no tenía un vínculo vivo. Vive así:
--
--   PENDIENTE  pulsó el botón y EX anunció el número al bot (el anuncio dura 24 horas; volver a
--              pulsar lo renueva sobre la misma fila).
--   ACTIVO     escribió desde ese número: el bot llamó a /vinculos y quedó vinculado.
--   REVOCADO   se cerró: dejó de recibir desde el portal, cambió el celular o el proceso terminó.
--   SUPRIMIDO  escribió «BAJA» al bot: el número no vuelve a recibir nada.
--
-- `motivo_cierre` usa los motivos de /revocaciones del contrato con el bot (DEJAR_DE_RECIBIR,
-- CAMBIO_CELULAR, PROCESO_TERMINADO), más BAJA, que no se revoca porque vino del bot. El cuarto
-- motivo del contrato, BORRADO_DATOS, no se guarda: el borrado se lleva las filas.
--
-- `referencia` es lo que viaja al bot como `postulacionRef`: opaca a propósito, ni el id interno
-- ni el uuid del portal.
--
-- El consentimiento apunta a su fila de `consentimiento` (texto, versión, fecha e IP), firmada
-- una vez por postulación y versión del texto WHATSAPP.
--
-- Las columnas de anuncio y revocación son lo que el sondeo reintenta cuando el bot no
-- responde.

CREATE TABLE vinculo_whatsapp (
    id                              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id                  bigint NOT NULL REFERENCES postulacion(id),
    persona_id                      bigint NOT NULL REFERENCES persona(id),
    referencia                      text NOT NULL UNIQUE,
    telefono                        text NOT NULL
        CONSTRAINT vinculo_whatsapp_telefono_check CHECK (telefono ~ '^\+[1-9][0-9]{7,14}$'),
    estado                          text NOT NULL
        CONSTRAINT vinculo_whatsapp_estado_check
        CHECK (estado IN ('PENDIENTE', 'ACTIVO', 'REVOCADO', 'SUPRIMIDO')),
    consentimiento_id               bigint NOT NULL REFERENCES consentimiento(id),
    anunciado_en                    timestamptz NOT NULL,
    anuncio_caduca_en               timestamptz NOT NULL,
    anuncio_confirmado_en           timestamptz,
    anuncio_intentos                integer NOT NULL DEFAULT 0,
    anuncio_proximo_intento_en      timestamptz,
    primer_wamid                    text,
    vinculado_en                    timestamptz,
    cerrado_en                      timestamptz,
    motivo_cierre                   text
        CONSTRAINT vinculo_whatsapp_motivo_check
        CHECK (motivo_cierre IS NULL OR motivo_cierre IN
               ('DEJAR_DE_RECIBIR', 'CAMBIO_CELULAR', 'PROCESO_TERMINADO', 'BAJA')),
    revocacion_enviada_en           timestamptz,
    revocacion_intentos             integer NOT NULL DEFAULT 0,
    revocacion_proximo_intento_en   timestamptz,
    creado_en                       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT vinculo_whatsapp_vivo_sin_cierre_check
        CHECK ((estado IN ('PENDIENTE', 'ACTIVO')) = (cerrado_en IS NULL)),
    CONSTRAINT vinculo_whatsapp_cerrado_con_motivo_check
        CHECK ((cerrado_en IS NULL) = (motivo_cierre IS NULL)),
    CONSTRAINT vinculo_whatsapp_activo_vinculado_check
        CHECK (estado <> 'ACTIVO' OR vinculado_en IS NOT NULL)
);

-- Un solo vínculo vivo por postulación: el doble clic renueva el anuncio, no crea otro.
CREATE UNIQUE INDEX vinculo_whatsapp_uno_vivo
    ON vinculo_whatsapp (postulacion_id)
    WHERE estado IN ('PENDIENTE', 'ACTIVO');

CREATE INDEX vinculo_whatsapp_telefono_vivo_idx
    ON vinculo_whatsapp (telefono)
    WHERE estado IN ('PENDIENTE', 'ACTIVO');

CREATE INDEX vinculo_whatsapp_persona_idx ON vinculo_whatsapp (persona_id);

CREATE INDEX vinculo_whatsapp_por_revocar_idx
    ON vinculo_whatsapp (revocacion_proximo_intento_en)
    WHERE cerrado_en IS NOT NULL AND revocacion_enviada_en IS NULL;

COMMENT ON TABLE vinculo_whatsapp IS
    'El vínculo entre el celular de un candidato y una postulación para contarle sus novedades '
    'por WhatsApp (V73). Un solo vínculo vivo (PENDIENTE o ACTIVO) por postulación.';


-- ============================================================================
-- 3 · La cola de avisos hacia el bot
-- ============================================================================
--
-- Solo los «te toca»: PRUEBA_DISPONIBLE y POSTULACION_AVANZA. Nacen en la misma transición que
-- el correo y la campana, si la postulación tiene un vínculo ACTIVO, y los envía un sondeo
-- después del commit, con espera creciente y hasta cinco intentos.
--
-- `id` es el `avisoId` que viaja al bot, su clave de idempotencia: reintentar manda el mismo.
-- Lo que se manda se guarda tal cual al encolar, para que un reintento sea idéntico al primero
-- aunque entretanto cambie el título de la vacante.
--
-- OMITIDO es «ya no tocaba»: el vínculo se cerró antes de que saliera.

CREATE TABLE aviso_whatsapp (
    id                      uuid PRIMARY KEY,
    postulacion_id          bigint NOT NULL REFERENCES postulacion(id),
    vinculo_whatsapp_id     bigint NOT NULL REFERENCES vinculo_whatsapp(id),
    transicion_estado_id    bigint NOT NULL REFERENCES transicion_estado(id),
    tipo                    text NOT NULL
        CONSTRAINT aviso_whatsapp_tipo_check
        CHECK (tipo IN ('PRUEBA_DISPONIBLE', 'POSTULACION_AVANZA')),
    estado                  text NOT NULL
        CONSTRAINT aviso_whatsapp_estado_check
        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO', 'OMITIDO')),
    telefono                text NOT NULL,
    referencia              text NOT NULL,
    nombre                  text NOT NULL,
    vacante                 text NOT NULL,
    texto                   text NOT NULL,
    intentos                integer NOT NULL DEFAULT 0,
    proximo_intento_en      timestamptz,
    ultimo_error            text,
    enviado_en              timestamptz,
    creado_en               timestamptz NOT NULL DEFAULT now(),
    actualizado_en          timestamptz NOT NULL DEFAULT now(),
    -- La red de la base debajo del «no se manda dos veces el mismo aviso»: aunque el servidor
    -- se reinicie o dos transiciones se pisen, una transición deja un solo aviso de cada tipo.
    CONSTRAINT aviso_whatsapp_una_vez_por_transicion UNIQUE (transicion_estado_id, tipo)
);

CREATE INDEX aviso_whatsapp_pendientes_idx
    ON aviso_whatsapp (proximo_intento_en)
    WHERE estado = 'PENDIENTE';

CREATE INDEX aviso_whatsapp_postulacion_idx ON aviso_whatsapp (postulacion_id);

COMMENT ON TABLE aviso_whatsapp IS
    'Los avisos «te toca» que EX manda al bot de WhatsApp (V73). Uno por transición y tipo; '
    'el id es el avisoId, la clave de idempotencia del bot.';


-- ============================================================================
-- 4 · Los números dados de baja
-- ============================================================================
--
-- Cuando el candidato escribe «BAJA» (solo esa palabra), el bot lo suprime para todo y para
-- siempre, y se lo cuenta a EX con /bajas. EX desvincula todo lo de ese número y no vuelve
-- a ofrecer el botón con él. Se guarda aparte del vínculo porque la baja es del número, no de
-- una postulación: puede llegar cuando ya no queda ningún vínculo vivo.

CREATE TABLE whatsapp_baja (
    telefono    text PRIMARY KEY
        CONSTRAINT whatsapp_baja_telefono_check CHECK (telefono ~ '^\+[1-9][0-9]{7,14}$'),
    dada_en     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE whatsapp_baja IS
    'Números que escribieron BAJA al bot de WhatsApp (V73): el portal ya no ofrece el botón con '
    'ellos.';


-- ============================================================================
-- 5 · Los textos legales
-- ============================================================================
--
-- 5a · El tipo WHATSAPP entra en el catálogo. Soltar el CHECK y volverlo a atar, como la V54.

ALTER TABLE texto_consentimiento DROP CONSTRAINT IF EXISTS texto_consentimiento_tipo_check;
ALTER TABLE texto_consentimiento ADD CONSTRAINT texto_consentimiento_tipo_check
    CHECK (tipo IN ('PLATAFORMA', 'PROCESO', 'FUTUROS_CONTACTOS', 'WHATSAPP'));

COMMENT ON COLUMN texto_consentimiento.tipo IS
    'PLATAFORMA = lo que se acepta con Renaser al crear la cuenta; PROCESO = lo que se acepta '
    'con LA EMPRESA de la vacante al postular; FUTUROS_CONTACTOS = el permiso opcional para '
    'avisar de otras vacantes; WHATSAPP = recibir por WhatsApp las novedades de un proceso, '
    'que se firma al pulsar «Escribir por WhatsApp» (V73). Todos de la plataforma.';

-- 5b · El consentimiento de WhatsApp, 1.0. Es literalmente lo que el portal pinta debajo del
-- botón: lo firmado tiene que ser lo leído. Solo para la plataforma, que es la única que lo
-- ofrece mientras dure la beta.

INSERT INTO texto_consentimiento (organizacion_id, tipo, version, texto, hash, publicado_en)
SELECT o.id, 'WHATSAPP', '1.0', t.texto, encode(digest(t.texto, 'sha256'), 'hex'), now()
FROM organizacion o,
     (VALUES ('Al escribirnos aceptas recibir por WhatsApp las novedades de este proceso. Puedes dejarlo cuando quieras.')) AS t(texto)
WHERE o.es_plataforma
  AND NOT EXISTS (
    SELECT 1 FROM texto_consentimiento ya
     WHERE ya.organizacion_id = o.id AND ya.tipo = 'WHATSAPP');

