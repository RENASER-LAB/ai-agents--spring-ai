-- Un informe en PDF por cada etapa del candidato (spec informe-pdf-por-etapa, 16/11/2026).
--
-- Los informes se arman cada vez que se piden con lo que ya está guardado: no se guarda ningún
-- PDF. Lo único nuevo que se guarda son los textos que escribe el «redactor del informe», un
-- agente de IA que NO califica: con las notas, sus explicaciones, las respuestas, los hallazgos y
-- las afirmaciones del CV ya guardados, escribe el resumen de la etapa, una línea por criterio y
-- una por respuesta, enfocadas en el resultado y que se entiendan sin leer la pregunta.
--
-- Ninguna nota cambia. Las filas que ya existen no se tocan.

-- ============================================================================
-- 1 · Los textos de cada etapa de cada postulación
-- ============================================================================
-- Una fila por postulación y etapa. «huella» resume los datos con los que se escribieron: si una
-- nota cambia (recalificación o ajuste a mano), la huella de los datos de hoy ya no coincide y el
-- informe vuelve a la explicación de la IA hasta que el redactor escriba los textos nuevos.
-- «huella_pedida» es lo último que se le pidió: el mismo pedido no se paga dos veces.
CREATE TABLE texto_informe (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id   bigint NOT NULL REFERENCES postulacion(id),
    etapa            text NOT NULL CHECK (etapa IN ('CV', 'EVALUACION', 'PRUEBA')),
    huella           text,
    resumen          text,
    criterios        text,
    preguntas        text,
    descartados      integer NOT NULL DEFAULT 0 CHECK (descartados >= 0),
    ejecucion_ia_id  bigint REFERENCES ejecucion_ia(id),
    huella_pedida    text,
    pedida_en        timestamptz,
    escrita_en       timestamptz,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT texto_informe_una_por_etapa UNIQUE (postulacion_id, etapa)
);

COMMENT ON TABLE texto_informe IS
    'Los textos del informe de cada etapa, escritos por el redactor del informe. No son notas: '
    'solo valen mientras los datos de la etapa tengan la misma huella.';
COMMENT ON COLUMN texto_informe.criterios IS
    'JSON: nombre exacto del criterio -> una línea. Lo que no pasó la comprobación no está.';
COMMENT ON COLUMN texto_informe.preguntas IS
    'JSON: una línea por respuesta, en el orden del anexo; null donde se descartó.';

