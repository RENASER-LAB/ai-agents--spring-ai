-- ============================================================================
-- 6 · Migrar lo que ya se sabe: dato_cv y los enlaces
-- ============================================================================
-- dato_cv es POR POSTULACION: una persona puede tener varias filas. Se toma la mas
-- reciente. Todo entra con origen CURRICULUM y SIN confirmar, porque nadie lo ha revisado:
-- el candidato lo vera marcado como «sacado de tu curriculum» y podra corregirlo. No se
-- puede presentar como si lo hubiera escrito el.
--
-- Se saltan las personas ya anonimizadas (tombstone del borrado 29733): crearles un perfil
-- seria resucitar datos que se pidieron borrar.
INSERT INTO perfil_candidato (persona_id, resumen, habilidades, experiencia_meses)
SELECT DISTINCT ON (u.persona_id)
       u.persona_id, d.perfil_resumen, d.habilidades, d.experiencia_meses_total
  FROM dato_cv d
  JOIN postulacion p ON p.id = d.postulacion_id
  JOIN usuario     u ON u.id = p.usuario_id
  JOIN persona     pe ON pe.id = u.persona_id
 WHERE pe.anonimizado_en IS NULL
 ORDER BY u.persona_id, d.actualizado_en DESC;

-- La experiencia: dato_cv guarda UN empleo y sin fechas, solo cuantos meses duro. La fecha
-- de inicio se reconstruye hacia atras desde la fecha del dato — es una aproximacion, y por
-- eso entra sin confirmar.
--
-- Sin esos meses NO se migra el empleo, aunque se sepan puesto y empresa: `desde` es NOT NULL
-- y rellenarlo con la fecha de hoy diria «empece hoy y sigo aqui», que es una trayectoria
-- inventada. Mejor un hueco que un dato falso — la misma regla que aplica el resto del perfil.
INSERT INTO experiencia_perfil (perfil_candidato_id, puesto, empresa, desde, origen, orden)
SELECT DISTINCT ON (pc.id)
       pc.id, d.ultimo_puesto, d.ultima_empresa,
       (d.actualizado_en - make_interval(months => d.ultima_meses_duracion))::date,
       'CURRICULUM', 1
  FROM dato_cv d
  JOIN postulacion p       ON p.id = d.postulacion_id
  JOIN usuario     u       ON u.id = p.usuario_id
  JOIN perfil_candidato pc ON pc.persona_id = u.persona_id
 WHERE d.ultimo_puesto IS NOT NULL AND d.ultima_empresa IS NOT NULL
   AND d.ultima_meses_duracion IS NOT NULL
 ORDER BY pc.id, d.actualizado_en DESC;

-- Los enlaces que ya se mandaron al postular. enlace_cv no distingue LinkedIn (entro como
-- OTRO) ni GitHub (entro como REPOSITORIO), asi que el tipo se deduce: REPOSITORIO pasa a
-- GITHUB, y OTRO pasa a LINKEDIN solo si la URL lo dice; lo demas se queda como estaba.
-- El DISTINCT ON respeta la UNIQUE (perfil, tipo, url) cuando la misma persona mando el
-- mismo enlace en dos postulaciones.
INSERT INTO enlace_perfil (perfil_candidato_id, tipo, url)
SELECT DISTINCT t.perfil_id, t.tipo_nuevo, t.url
  FROM (
    SELECT pc.id AS perfil_id,
           CASE
               WHEN e.tipo = 'REPOSITORIO' THEN 'GITHUB'
               WHEN e.tipo = 'OTRO' AND e.url ILIKE '%linkedin.com%' THEN 'LINKEDIN'
               -- enlace_cv.tipo ADMITE NULL (V7) y esta columna es NOT NULL: sin el
               -- coalesce, una sola fila sin tipo impedia que esta migracion aplicara.
               -- Los demas valores de aquel CHECK —PORTAFOLIO, PUBLICACION, PRODUCTO,
               -- OTRO— existen igual en el nuevo, asi que pasan tal cual.
               ELSE COALESCE(e.tipo, 'OTRO')
           END AS tipo_nuevo,
           e.url
      FROM enlace_cv e
      JOIN cv           c  ON c.id = e.cv_id
      JOIN postulacion  p  ON p.id = c.postulacion_id
      JOIN usuario      u  ON u.id = p.usuario_id
      JOIN perfil_candidato pc ON pc.persona_id = u.persona_id
     WHERE e.url NOT LIKE '[eliminado%'
  ) t;

