-- ============================================================================
-- El perfil del candidato: sus datos dejan de morir con cada postulacion
-- ============================================================================
--
-- Hasta hoy, todo lo que se sabia de un candidato colgaba de UNA postulacion: si postulaba
-- a tres vacantes, su curriculum se leia (y se pagaba) tres veces y sus datos quedaban en
-- tres filas de dato_cv sin relacion entre si. No habia forma de decir «este es Juan y esta
-- es su trayectoria».
--
-- Este perfil cuelga de PERSONA, no de usuario, y es una decision de fondo: el usuario
-- existe una vez por organizacion (UNIQUE (persona_id, organizacion_id)), asi que un perfil
-- por usuario obligaria al candidato a llenarlo una vez por empresa. Colgando de persona
-- sale el modelo de los portales de empleo: una persona, un perfil, muchas empresas.
--
-- Tres reglas que el esquema hace cumplir o deja rastro para cumplir:
--   - Cada dato sabe de donde vino (origen PERSONA o CURRICULUM) y si la persona lo
--     confirmo (confirmado_en). Lo que la IA lee se PROPONE; nunca pisa lo confirmado.
--   - El perfil no puntua: ninguna de estas tablas participa en notas ni rankings.
--   - La pretension salarial es un rango con moneda, o nada: un minimo suelto no
--     significa nada y una cifra exacta se lee como ultimatum.
--
-- El diseño completo, con los requisitos y las historias, esta en
-- docs/PROPUESTA-PERFIL-DEL-CANDIDATO.md.

-- ============================================================================
-- 1 · Los dos catalogos
-- ============================================================================
-- Cerrados y en tabla, no en CHECK: los niega o amplia el negocio, no una migracion.

