-- El propósito de la empresa, a la vista del candidato (spec proposito-de-la-empresa, 16/11/2026).
--
-- Cada empresa guarda cómo se presenta: logo, portada, sector, tamaño, año de fundación,
-- «Quiénes somos», su propósito, sus beneficios, el enlace a su video de presentación, su
-- página web y sus redes. Lo llena desde el panel («Perfil de la empresa») y el candidato lo
-- ve en el portal, junto a cada vacante y en el perfil público de la empresa.
--
-- ⚠️ `proposito_empresa` se llama así a propósito: `vacante.proposito` es el propósito DEL
-- PUESTO («El resultado que esperamos») y no cambia. Son dos cosas y no se confunden.
--
-- Las empresas que existen quedan sin datos: ninguna vacante cambia hasta que su empresa guarda.

-- ============================================================================
-- 1 · La presentación, en la propia organización
-- ============================================================================
-- Todo opcional. Un campo vacío es NULL, nunca una cadena vacía: por eso los CHECK piden al
-- menos un carácter.
--
-- El año de fundación solo tiene suelo en la base (1800). El techo es «el año actual» y lo
-- comprueba la aplicación: un CHECK con CURRENT_DATE no es inmutable —Postgres da por hecho
-- que un CHECK lo es— y una copia restaurada años después podría rechazar filas que eran
-- válidas al guardarse.
ALTER TABLE organizacion
    ADD COLUMN proposito_empresa  text
        CHECK (proposito_empresa IS NULL OR char_length(proposito_empresa) BETWEEN 1 AND 1500),
    ADD COLUMN quienes_somos      text
        CHECK (quienes_somos IS NULL OR char_length(quienes_somos) BETWEEN 1 AND 1500),
    ADD COLUMN sector             text
        CHECK (sector IS NULL OR char_length(sector) BETWEEN 1 AND 60),
    ADD COLUMN tamano             text
        CHECK (tamano IS NULL OR tamano IN ('DE_1_A_10', 'DE_11_A_50', 'DE_51_A_200',
                                            'DE_201_A_500', 'DE_501_A_1000', 'MAS_DE_1000')),
    ADD COLUMN anio_fundacion     integer
        CHECK (anio_fundacion IS NULL OR anio_fundacion >= 1800),
    ADD COLUMN video_presentacion text
        CHECK (video_presentacion IS NULL OR char_length(video_presentacion) BETWEEN 1 AND 500),
    ADD COLUMN pagina_web         text
        CHECK (pagina_web IS NULL OR char_length(pagina_web) BETWEEN 1 AND 500),
    -- El logo y la portada son filas de `archivo` de la propia empresa, ya re-codificadas en el
    -- servidor (sin metadatos). Son los primeros archivos de EX que se ven sin cuenta, y solo
    -- se sirven por /api/v1/portal/empresas/{codigo}/imagenes/{logo|portada}.
    ADD COLUMN logo_archivo_id    bigint REFERENCES archivo(id),
    ADD COLUMN portada_archivo_id bigint REFERENCES archivo(id);

COMMENT ON COLUMN organizacion.proposito_empresa IS
    'Por qué existe la empresa, como la cuenta ella. No es vacante.proposito, que es el del puesto.';
COMMENT ON COLUMN organizacion.video_presentacion IS
    'El enlace a su video de YouTube o Vimeo, tal como se pegó. El portal lo reconstruye a partir '
    'del servicio y del identificador, nunca copiando este texto en la página.';

-- ============================================================================
-- 2 · Los beneficios: hasta 12 por empresa, de 40 caracteres
-- ============================================================================
-- Guardar los reemplaza todos (se borran y se escriben en su orden): no tienen historia propia,
-- y el cambio queda en la auditoría.
CREATE TABLE organizacion_beneficio (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizacion(id),
    texto           text NOT NULL CHECK (char_length(texto) BETWEEN 1 AND 40),
    orden           integer NOT NULL CHECK (orden BETWEEN 1 AND 12),
    UNIQUE (organizacion_id, orden)
);

-- ============================================================================
-- 3 · Las redes: cinco fijas, una fila por empresa y red
-- ============================================================================
-- Una red vacía es una fila que no existe. El tablón carga las de todas las empresas del lote
-- en una sola consulta, nunca una por vacante: de ahí el índice por organización.
CREATE TABLE organizacion_red_social (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizacion(id),
    red             text NOT NULL
        CHECK (red IN ('FACEBOOK', 'INSTAGRAM', 'LINKEDIN', 'TIKTOK', 'YOUTUBE')),
    enlace          text NOT NULL CHECK (char_length(enlace) BETWEEN 1 AND 500),
    UNIQUE (organizacion_id, red)
);

-- ============================================================================
-- 4 · El video propio de un puesto
-- ============================================================================
-- Opcional, con las mismas reglas que el de la empresa. Vacío, la vacante usa el de la empresa.
-- Cambiarlo con la vacante publicada es una corrección normal: se audita y no se avisa.
ALTER TABLE vacante
    ADD COLUMN video_presentacion text
        CHECK (video_presentacion IS NULL OR char_length(video_presentacion) BETWEEN 1 AND 500);

-- ============================================================================
-- 5 · El permiso
-- ============================================================================
-- editar_presentacion_empresa: el módulo «Perfil de la empresa» del panel. Lo tienen Talento,
-- Dirección y Administrador (decisión del 16/11/2026) en TODAS las organizaciones que ya
-- existen, no solo en la de la plataforma: una empresa dada de alta antes de hoy tiene sus
-- propios roles. Las empresas futuras lo reciben con la copia de roles del alta
-- (ServicioPlataformaImpl#sembrar), porque la plataforma ya lo tiene por esta sentencia.
INSERT INTO permiso (codigo, etiqueta, grupo, orden) VALUES
    ('editar_presentacion_empresa', 'Editar el perfil de la empresa', 'CONFIGURACION', 16);

INSERT INTO rol_permiso (rol_id, permiso_id, alcance)
SELECT r.id, p.id, 'TODO'
FROM rol r
JOIN permiso p ON p.codigo = 'editar_presentacion_empresa'
WHERE r.codigo IN ('TALENTO', 'DIRECCION', 'ADMINISTRADOR')
  AND NOT EXISTS (SELECT 1 FROM rol_permiso ya
                  WHERE ya.rol_id = r.id AND ya.permiso_id = p.id);
