-- ============================================================================
-- 4 · PRUEBA_DISPONIBLE deja de decir «desde este correo»
-- ============================================================================
-- El texto original (V29) dice «Tienes {{plazo}} desde este correo.», y ya no es verdad: el
-- reloj arranca al abrir la prueba, no al recibir el correo, y desde la V70 {{plazo}} dice el
-- tiempo y la fecha límite («90 minutos desde que la empieces, hasta el vie 10/10 a las 23:59»).
--
-- La versión activa de producción se editó a mano y no está en ninguna migración, así que esto
-- funciona con cualquier texto: solo toca los que dicen «desde este correo», y de ellos solo esa
-- frase. Lo demás —la línea de cómo entrar al portal, la firma— se queda como esté.
--
-- Alcance: PRUEBA_DISPONIBLE de cada organización y los textos propios que alguna vacante use
-- para ese aviso (plantilla_correo_vacante con aviso_codigo = 'PRUEBA_DISPONIBLE').
--
-- La sustitución, en tres pasos y en este orden:
--   a) «Tienes {{plazo}} desde este correo» → «Tienes {{plazo}}» (la de la V29; el punto se queda);
--   b) «{{plazo}} desde este correo» → «{{plazo}}» (cualquier otra frase que siga a la variable);
--   c) cualquier otra frase que aún diga «desde este correo», con o sin mayúsculas, se sustituye
--      entera por la del texto de referencia: «Tienes {{plazo}}.».
--
-- Como siempre que se edita un texto, se publica una versión nueva y la anterior se conserva
-- desactivada: cada correo enviado apunta a la versión con la que salió.
WITH en_alcance AS (
    SELECT DISTINCT ON (pc.organizacion_id, pc.codigo)
           pc.organizacion_id, pc.codigo, pc.asunto, pc.cuerpo
      FROM plantilla_correo pc
     WHERE pc.es_activa
       AND (pc.codigo = 'PRUEBA_DISPONIBLE'
            OR EXISTS (SELECT 1
                         FROM plantilla_correo_vacante pcv
                         JOIN vacante v ON v.id = pcv.vacante_id
                        WHERE pcv.aviso_codigo = 'PRUEBA_DISPONIBLE'
                          AND pcv.plantilla_codigo = pc.codigo
                          AND v.organizacion_id = pc.organizacion_id))
     ORDER BY pc.organizacion_id, pc.codigo, pc.version DESC
)
INSERT INTO plantilla_correo (organizacion_id, codigo, version, asunto, cuerpo, es_activa, creado_en)
SELECT a.organizacion_id,
       a.codigo,
       (SELECT max(t.version) + 1 FROM plantilla_correo t
         WHERE t.organizacion_id = a.organizacion_id AND t.codigo = a.codigo),
       regexp_replace(
           replace(replace(a.asunto, 'Tienes {{plazo}} desde este correo', 'Tienes {{plazo}}'),
                   '{{plazo}} desde este correo', '{{plazo}}'),
           '[^.!?[:space:]][^.!?\n]*desde este correo[^.!?\n]*[.!?]?', 'Tienes {{plazo}}.', 'gi'),
       regexp_replace(
           replace(replace(a.cuerpo, 'Tienes {{plazo}} desde este correo', 'Tienes {{plazo}}'),
                   '{{plazo}} desde este correo', '{{plazo}}'),
           '[^.!?[:space:]][^.!?\n]*desde este correo[^.!?\n]*[.!?]?', 'Tienes {{plazo}}.', 'gi'),
       true,
       now()
  FROM en_alcance a
 WHERE a.cuerpo ILIKE '%desde este correo%' OR a.asunto ILIKE '%desde este correo%';

-- Y se jubilan las activas que todavía lo dicen. Nunca la más nueva de su código: es la que se
-- acaba de publicar, y si la sustitución hubiera dejado algo, apagarla dejaría a la empresa sin
-- ningún texto para el aviso.
UPDATE plantilla_correo pc
   SET es_activa = false
 WHERE pc.es_activa
   AND (pc.cuerpo ILIKE '%desde este correo%' OR pc.asunto ILIKE '%desde este correo%')
   AND (pc.codigo = 'PRUEBA_DISPONIBLE'
        OR EXISTS (SELECT 1
                     FROM plantilla_correo_vacante pcv
                     JOIN vacante v ON v.id = pcv.vacante_id
                    WHERE pcv.aviso_codigo = 'PRUEBA_DISPONIBLE'
                      AND pcv.plantilla_codigo = pc.codigo
                      AND v.organizacion_id = pc.organizacion_id))
   AND pc.version < (SELECT max(t.version) FROM plantilla_correo t
                      WHERE t.organizacion_id = pc.organizacion_id AND t.codigo = pc.codigo);

