-- La prueba al instante, la campana en cada etapa y los recordatorios (07/10/2026).
--
-- Muchos candidatos se pierden entre una etapa y la siguiente: entregan el banco, leen «te
-- avisaremos cuando avance», cierran la página y no vuelven. Esta migración prepara tres de
-- los cuatro cambios de specs/la-prueba-al-instante-y-avisos-de-etapa.md (el cuarto, abrir la
-- prueba al instante, no toca el esquema):
--
--   1. Cada transición recuerda CÓMO se enteró el candidato. Es lo que permite que un
--      recordatorio no le cuente a nadie lo que el equipo decidió no contarle.
--   2. Una tabla que dice qué recordatorio salió para qué turno, para no repetirlo nunca.
--   3. Los parámetros y los dos textos de correo de los recordatorios, en todas las empresas.
--   4. El texto de PRUEBA_DISPONIBLE deja de decir «desde este correo», que ya no es verdad.

-- ============================================================================
-- 1 · Cómo se enteró el candidato de cada transición
-- ============================================================================
-- Hasta hoy solo quedaba escrito en el motivo («· sin avisar al candidato») y en la auditoría,
-- y el motivo no siempre existe: una transición del sistema callada no dejaba marca ninguna.
--
-- Vacía en todo lo anterior a esta migración, y eso es a propósito: los recordatorios solo
-- cuentan los turnos que se abren con CORREO, así que un turno abierto antes del despliegue
-- nunca recibe un recordatorio de golpe. Sin esto, el primer día saldría una ráfaga de correos
-- a todo el que lleva más de 24 horas en su turno.
--
-- ⚠️ `transicion_estado` es inmutable (trigger de la V6), pero añadir una columna no actualiza
-- ninguna fila: las viejas leen NULL sin que el trigger salte.
ALTER TABLE transicion_estado
    ADD COLUMN aviso_al_candidato text
        CONSTRAINT transicion_aviso_al_candidato_check
        CHECK (aviso_al_candidato IS NULL
               OR aviso_al_candidato IN ('CORREO', 'NINGUNO', 'POR_LA_CAMPANA'));

COMMENT ON COLUMN transicion_estado.aviso_al_candidato IS
    'Cómo se enteró el candidato: CORREO (el correo y la campana), NINGUNO (el equipo decidió '
    'no contárselo) o POR_LA_CAMPANA (solo el aviso propio, como el cierre por vacante '
    'eliminada). Vacía en las transiciones anteriores a la V70.';

-- ============================================================================
-- 2 · Qué recordatorio salió para qué turno
-- ============================================================================
-- El turno es la transición que lo abrió: si el candidato vuelve a entrar en el mismo estado
-- —se le reabre la evaluación, se le retrocede—, es otra transición y otro turno, con sus dos
-- recordatorios.
--
-- TRAS_ENTRAR sale una vez por turno. ANTES_DEL_PLAZO, una vez por turno y por fecha: si la
-- fecha se mueve después del recordatorio, puede volver a salir para la nueva, una sola vez.
--
-- OMITIDO es «este ya no sale»: cuando el del plazo se adelanta al de las 24 horas (o caen a
-- menos de 12 horas el uno del otro), el de las 24 horas se da por gastado. Queda escrito para
-- que el sondeo no lo vuelva a considerar cada minuto.
CREATE TABLE recordatorio_enviado (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id       bigint NOT NULL REFERENCES postulacion(id),
    transicion_estado_id bigint NOT NULL REFERENCES transicion_estado(id),
    tipo                 text NOT NULL
        CONSTRAINT recordatorio_enviado_tipo_check
        CHECK (tipo IN ('TRAS_ENTRAR', 'ANTES_DEL_PLAZO')),
    -- La fecha que se recordó. Solo la lleva el del plazo.
    plazo_en             timestamptz,
    resultado            text NOT NULL
        CONSTRAINT recordatorio_enviado_resultado_check
        CHECK (resultado IN ('ENVIADO', 'OMITIDO')),
    creado_en            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT recordatorio_enviado_plazo_check
        CHECK ((tipo = 'ANTES_DEL_PLAZO') = (plazo_en IS NOT NULL))
);

-- La red de la base debajo del «¿ya salió?» del código: reiniciar el servidor, o dos sondeos
-- a la vez, no pueden mandar el mismo recordatorio dos veces.
CREATE UNIQUE INDEX recordatorio_tras_entrar_una_vez
    ON recordatorio_enviado (transicion_estado_id)
    WHERE tipo = 'TRAS_ENTRAR';

CREATE UNIQUE INDEX recordatorio_antes_del_plazo_una_vez
    ON recordatorio_enviado (transicion_estado_id, plazo_en)
    WHERE tipo = 'ANTES_DEL_PLAZO';

CREATE INDEX recordatorio_enviado_postulacion_idx ON recordatorio_enviado (postulacion_id);

COMMENT ON TABLE recordatorio_enviado IS
    'Qué recordatorio salió (o se dio por omitido) para qué turno de una postulación. Es lo que '
    'impide repetirlo al reiniciar el servidor (V70).';

-- ============================================================================
-- 3 · Los parámetros y los textos de los recordatorios
-- ============================================================================
-- En TODAS las organizaciones y no solo en la plataforma. ServicioCorreo.enviar no cae a la
-- plataforma cuando a una empresa le falta un texto, y un parámetro que no existe no se puede
-- editar desde el panel (editarParametro no crea filas). Las empresas que se den de alta
-- después los copian de la plataforma, como copian todos los demás.
INSERT INTO parametro (organizacion_id, codigo, valor, tipo, descripcion, creado_en)
SELECT o.id, 'recordatorios_activos', 'true', 'BOOLEANO',
       'Si se manda a los candidatos un recordatorio (correo y campana) cuando no han '
           || 'entregado su evaluación o no han empezado su prueba',
       now()
  FROM organizacion o
 WHERE NOT EXISTS (SELECT 1 FROM parametro p
                    WHERE p.organizacion_id = o.id AND p.codigo = 'recordatorios_activos');

INSERT INTO parametro (organizacion_id, codigo, valor, tipo, descripcion, creado_en)
SELECT o.id, 'recordatorio_horas_tras_el_turno', '24', 'ENTERO',
       'Horas desde que le toca la evaluación o la prueba hasta el primer recordatorio',
       now()
  FROM organizacion o
 WHERE NOT EXISTS (SELECT 1 FROM parametro p
                    WHERE p.organizacion_id = o.id
                      AND p.codigo = 'recordatorio_horas_tras_el_turno');

INSERT INTO parametro (organizacion_id, codigo, valor, tipo, descripcion, creado_en)
SELECT o.id, 'recordatorio_horas_antes_del_plazo', '24', 'ENTERO',
       'Horas antes de que venza la evaluación o la prueba en que sale el segundo recordatorio',
       now()
  FROM organizacion o
 WHERE NOT EXISTS (SELECT 1 FROM parametro p
                    WHERE p.organizacion_id = o.id
                      AND p.codigo = 'recordatorio_horas_antes_del_plazo');

