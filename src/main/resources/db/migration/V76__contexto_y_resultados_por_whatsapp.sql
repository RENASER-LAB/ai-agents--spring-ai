-- Contexto de vacantes y resultados por WhatsApp (19/10/2026). Ver
-- specs/Ready/contexto-y-resultados-por-whatsapp.md y el contrato v2
-- (docs/CONTRATO-CONTEXTO-Y-RESULTADOS-POR-WHATSAPP-V2.md).
--
-- Dos cosas nuevas, las dos aditivas: no se toca ninguna tabla de la V73.
--
--   1. El resultado de una postulación que terminó con un vínculo de WhatsApp ACTIVO: lo que
--      el bot puede consultar durante 30 días (C-2). Es la proyección pública mínima —tipo,
--      fecha y revisión—, nunca notas, motivos internos ni la ficha.
--   2. La bandeja de salida de los eventos v2 hacia el bot (POST /v1/ex/resultados): un
--      RESULTADO al terminar o una CONVOCATORIA_CERRADA al cerrar la vacante. Se escriben en la
--      MISMA transacción que el hecho, así que un reinicio después de confirmar no los pierde.
--
-- El productor v2 va detrás de app.whatsapp.productor-v2, apagado por defecto: con él apagado
-- no nace ningún evento y EX se comporta como v1. Al encenderlo no se mandan hechos anteriores:
-- solo salen los eventos escritos desde entonces.


-- ============================================================================
-- 1 · El resultado consultable
-- ============================================================================
--
-- Una fila por postulación, y solo si al terminar tenía un vínculo ACTIVO (había escrito al
-- bot). Los vínculos legados ya cerrados no se convierten en resultados: no hay una fuente que
-- diga qué resultado era ni que la persona tuviera acceso al terminar.
--
-- `consultable_hasta` es la fecha del hecho más 30 días: una corrección no lo alarga.
-- `acceso_revocado_*` lo retira antes: BAJA del número o cambio del celular de la cuenta. El
-- borrado de datos se lleva la fila entera.
--
-- `revision` crece con cada corrección del mismo resultado; es la que el bot compara para no
-- pisar un dato nuevo con uno viejo. Va aparte de la revisión de la convocatoria.

CREATE TABLE resultado_whatsapp (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id          bigint NOT NULL REFERENCES postulacion(id),
    vinculo_whatsapp_id     bigint NOT NULL REFERENCES vinculo_whatsapp(id),
    tipo                    text NOT NULL
        CONSTRAINT resultado_whatsapp_tipo_check
        CHECK (tipo IN ('CONTRATADO', 'NO_CONTINUA', 'CERRADA')),
    fecha                   timestamptz NOT NULL,
    revision                integer NOT NULL DEFAULT 1
        CONSTRAINT resultado_whatsapp_revision_check CHECK (revision > 0),
    es_correccion           boolean NOT NULL DEFAULT false,
    consultable_hasta       timestamptz NOT NULL,
    acceso_revocado_en      timestamptz,
    acceso_revocado_motivo  text
        CONSTRAINT resultado_whatsapp_motivo_check
        CHECK (acceso_revocado_motivo IS NULL
               OR acceso_revocado_motivo IN ('BAJA', 'CAMBIO_CELULAR', 'DEJAR_DE_RECIBIR')),
    creado_en               timestamptz NOT NULL DEFAULT now(),
    actualizado_en          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT resultado_whatsapp_una_por_postulacion UNIQUE (postulacion_id),
    CONSTRAINT resultado_whatsapp_treinta_dias_check
        CHECK (consultable_hasta <= fecha + interval '30 days'),
    CONSTRAINT resultado_whatsapp_revocado_con_motivo_check
        CHECK ((acceso_revocado_en IS NULL) = (acceso_revocado_motivo IS NULL))
);

CREATE INDEX resultado_whatsapp_vinculo_idx ON resultado_whatsapp (vinculo_whatsapp_id);

CREATE INDEX resultado_whatsapp_vigentes_idx
    ON resultado_whatsapp (consultable_hasta)
    WHERE acceso_revocado_en IS NULL;

COMMENT ON TABLE resultado_whatsapp IS
    'El resultado de una postulación que terminó con un vínculo de WhatsApp activo (V76): lo '
    'que el bot puede consultar durante 30 días. Solo tipo, fecha y revisión.';


-- ============================================================================
-- 2 · La bandeja de salida de los eventos v2
-- ============================================================================
--
-- `id` es el `eventoId` (UUIDv7) que viaja al bot: los reintentos mandan el mismo, con el
-- mismo contenido, que se guarda tal cual al escribirlo (las fechas, en milisegundos).
--
-- Una sola fila por postulación, tipo y revisión: el mismo hecho dos veces no deja dos
-- pendientes. Las dos revisiones —la del resultado y la de la convocatoria— viven en la misma
-- columna, separadas por el tipo.
--
-- `aviso_autorizado` y `aviso_caduca_en` son la autorización limitada del aviso final: solo
-- con el vínculo ACTIVO al confirmarse el hecho, y como mucho 24 horas desde él (C-6).
--
--   PENDIENTE  por mandar (o reintentando).
--   ACEPTADO   el bot respondió 202. Aceptado, no entregado al WhatsApp de la persona.
--   FALLIDO    el bot lo rechazó para siempre (404 ruta_no_disponible con el bot en v1,
--              409 evento_distinto…) o se acabaron los intentos.
--   OMITIDO    ya no tocaba: caducó, BAJA, revocado o borrado. `motivo` dice cuál.

CREATE TABLE evento_whatsapp (
    id                              uuid PRIMARY KEY,
    postulacion_id                  bigint NOT NULL REFERENCES postulacion(id),
    vinculo_whatsapp_id             bigint NOT NULL REFERENCES vinculo_whatsapp(id),
    tipo                            text NOT NULL
        CONSTRAINT evento_whatsapp_tipo_check
        CHECK (tipo IN ('RESULTADO', 'CONVOCATORIA_CERRADA')),
    revision                        integer NOT NULL
        CONSTRAINT evento_whatsapp_revision_check CHECK (revision > 0),
    estado                          text NOT NULL
        CONSTRAINT evento_whatsapp_estado_check
        CHECK (estado IN ('PENDIENTE', 'ACEPTADO', 'FALLIDO', 'OMITIDO')),
    telefono                        text NOT NULL,
    referencia                      text NOT NULL,
    nombre                          text NOT NULL,
    vacante                         text NOT NULL,
    ocurrido_en                     timestamptz NOT NULL,
    resultado_tipo                  text
        CONSTRAINT evento_whatsapp_resultado_tipo_check
        CHECK (resultado_tipo IS NULL OR resultado_tipo IN ('CONTRATADO', 'NO_CONTINUA', 'CERRADA')),
    resultado_fecha                 timestamptz,
    resultado_es_correccion         boolean NOT NULL DEFAULT false,
    resultado_consultable_hasta     timestamptz,
    convocatoria_cerrada_en         timestamptz,
    aviso_autorizado                boolean NOT NULL,
    aviso_caduca_en                 timestamptz NOT NULL,
    cierra_vinculo                  boolean NOT NULL,
    intentos                        integer NOT NULL DEFAULT 0,
    proximo_intento_en              timestamptz,
    ultimo_error                    text,
    motivo                          text,
    aceptado_en                     timestamptz,
    creado_en                       timestamptz NOT NULL DEFAULT now(),
    actualizado_en                  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT evento_whatsapp_uno_por_revision UNIQUE (postulacion_id, tipo, revision),
    CONSTRAINT evento_whatsapp_resultado_completo_check
        CHECK ((tipo = 'RESULTADO') = (resultado_tipo IS NOT NULL AND resultado_fecha IS NOT NULL
                                        AND resultado_consultable_hasta IS NOT NULL)),
    CONSTRAINT evento_whatsapp_convocatoria_completa_check
        CHECK ((tipo = 'CONVOCATORIA_CERRADA') = (convocatoria_cerrada_en IS NOT NULL)),
    CONSTRAINT evento_whatsapp_cierra_solo_el_resultado_check
        CHECK (cierra_vinculo = (tipo = 'RESULTADO')),
    CONSTRAINT evento_whatsapp_veinticuatro_horas_check
        CHECK (aviso_caduca_en <= ocurrido_en + interval '24 hours')
);

CREATE INDEX evento_whatsapp_pendientes_idx
    ON evento_whatsapp (proximo_intento_en)
    WHERE estado = 'PENDIENTE';

CREATE INDEX evento_whatsapp_vinculo_idx ON evento_whatsapp (vinculo_whatsapp_id);

CREATE INDEX evento_whatsapp_telefono_pendiente_idx
    ON evento_whatsapp (telefono)
    WHERE estado = 'PENDIENTE';

COMMENT ON TABLE evento_whatsapp IS
    'Los eventos v2 de EX hacia el bot de WhatsApp (V76): RESULTADO y CONVOCATORIA_CERRADA. '
    'Bandeja de salida escrita en la misma transacción que el hecho; el id es el eventoId.';
