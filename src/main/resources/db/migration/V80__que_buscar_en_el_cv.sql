-- «Qué buscar en el CV» (spec que-buscar-en-el-cv, 21/10/2026).
--
-- Quien crea la vacante escribe, en una casilla privada, hasta seis cosas concretas que busca en
-- el CV. Un agente nuevo (BUSQUEDA_CV) las busca en cada CV que la IA califica y dice, por línea,
-- si la persona LA TIENE (con la frase del CV que lo prueba), LA MENCIONA sin detalle o NO
-- APARECE. El resultado entra en la nota del CV con el peso que dice la versión de pesos.
--
-- ⚠️ Nada de esto es público: las líneas NO van en vacante.requisitos ni en ninguna columna que
-- lean el portal, «Mis procesos», WhatsApp, los correos o los agentes que escriben lo que ve el
-- candidato. Viven en sus propias tablas, que solo lee el panel.
--
-- Las vacantes que existen no tienen líneas: nada cambia en ellas ni en sus notas.

-- ============================================================================
-- 1 · Las líneas de cada vacante
-- ============================================================================
-- Una fila por línea. Editar las líneas archiva TODAS las vivas y crea las nuevas con la versión
-- siguiente: un resultado que llegue de una versión vieja se reconoce por su número y se descarta.
-- Lo que se retira se archiva, no se borra.
CREATE TABLE linea_busqueda_cv (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacante_id      bigint NOT NULL REFERENCES vacante(id),
    version_lineas  integer NOT NULL CHECK (version_lineas >= 1),
    orden           integer NOT NULL CHECK (orden BETWEEN 1 AND 6),
    texto           text NOT NULL CHECK (char_length(texto) BETWEEN 1 AND 200),
    creado_en       timestamptz NOT NULL DEFAULT now(),
    archivada_en    timestamptz
);
-- Como mucho seis vivas por vacante, una por puesto en la lista.
CREATE UNIQUE INDEX linea_busqueda_cv_viva_idx
    ON linea_busqueda_cv (vacante_id, orden) WHERE archivada_en IS NULL;
CREATE INDEX linea_busqueda_cv_vacante_idx ON linea_busqueda_cv (vacante_id, version_lineas);

COMMENT ON TABLE linea_busqueda_cv IS
    'Qué buscar en el CV: lo que la empresa busca en cada CV de la vacante. Privado: no sale '
    'ni en el portal ni a los agentes que escriben para el candidato.';

-- ============================================================================
-- 2 · La búsqueda de cada persona
-- ============================================================================
-- Cómo acabó la búsqueda en el CV de una persona, con la versión de las líneas que se buscó.
-- TERMINADA trae sus resultados; SIN_TEXTO es el CV del que el extractor no saca texto (menos de
-- 40 caracteres o un .doc viejo), con su motivo: no se llama a la IA ni se reintenta.
-- Pendiente, en curso y fallida se leen del trabajo de la cola (trabajo_ia del agente BUSQUEDA_CV).
CREATE TABLE busqueda_cv (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id   bigint NOT NULL REFERENCES postulacion(id),
    version_lineas   integer NOT NULL CHECK (version_lineas >= 1),
    estado           text NOT NULL CHECK (estado IN ('TERMINADA', 'SIN_TEXTO')),
    motivo           text,
    ejecucion_ia_id  bigint REFERENCES ejecucion_ia(id),
    creado_en        timestamptz NOT NULL DEFAULT now(),
    archivada_en     timestamptz
);
CREATE UNIQUE INDEX busqueda_cv_viva_idx
    ON busqueda_cv (postulacion_id) WHERE archivada_en IS NULL;

-- ============================================================================
-- 3 · El resultado por persona y línea
-- ============================================================================
-- «Lo tiene» exige la frase literal del CV: el servidor la busca en el texto y, si no está, guarda
-- «Lo menciona» sin frase. Como mucho un resultado vivo por persona y línea.
CREATE TABLE resultado_busqueda_cv (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    busqueda_cv_id        bigint NOT NULL REFERENCES busqueda_cv(id),
    postulacion_id        bigint NOT NULL REFERENCES postulacion(id),
    linea_busqueda_cv_id  bigint NOT NULL REFERENCES linea_busqueda_cv(id),
    version_lineas        integer NOT NULL CHECK (version_lineas >= 1),
    estado                text NOT NULL CHECK (estado IN ('TIENE', 'MENCIONA', 'NO_APARECE')),
    frase_cv              text CHECK (frase_cv IS NULL OR char_length(frase_cv) <= 1000),
    nota                  text,
    pregunta              text,
    ejecucion_ia_id       bigint REFERENCES ejecucion_ia(id),
    creado_en             timestamptz NOT NULL DEFAULT now(),
    archivado_en          timestamptz,
    CONSTRAINT resultado_busqueda_cv_tiene_con_frase CHECK (estado <> 'TIENE' OR frase_cv IS NOT NULL)
);
CREATE UNIQUE INDEX resultado_busqueda_cv_vivo_idx
    ON resultado_busqueda_cv (postulacion_id, linea_busqueda_cv_id) WHERE archivado_en IS NULL;
CREATE INDEX resultado_busqueda_cv_busqueda_idx ON resultado_busqueda_cv (busqueda_cv_id);

-- ============================================================================
-- 4 · El peso, en la versión de pesos
-- ============================================================================
-- En % de la nota del CV: nota del CV = criterios generales × (1 − p) + lo buscado × p. Igual para
-- todos los niveles. Todas las versiones que existen —también las copias de las empresas— quedan
-- en 25, que no tiene efecto hasta que una vacante tenga líneas. Publicada, no se edita: para
-- cambiarlo se crea otra versión y se elige en la vacante, que recalcula a todos (V74).
ALTER TABLE version_pesos
    ADD COLUMN peso_busqueda_cv numeric(5,2) NOT NULL DEFAULT 25
        CONSTRAINT version_pesos_peso_busqueda_cv_check CHECK (peso_busqueda_cv BETWEEN 0 AND 50);

COMMENT ON COLUMN version_pesos.peso_busqueda_cv IS
    'Cuánto pesa «Qué buscar en el CV» dentro de la nota del CV, de 0 a 50. 25 por defecto.';

-- ============================================================================
-- 5 · La rebúsqueda va por su propio carril
-- ============================================================================
-- Editar las líneas con candidatos dentro vuelve a buscar en todos los CV. Con un modo propio no
-- entra en la barrera del Perfil Integral (que al terminar movería a la gente de etapa) ni en el
-- «cómo va» del retrato: al llegar, recalcula sin mover a nadie.
DO $$
DECLARE restriccion text;
BEGIN
    FOR restriccion IN
        SELECT conname FROM pg_constraint
         WHERE conrelid = 'trabajo_ia'::regclass AND contype = 'c'
           AND pg_get_constraintdef(oid) LIKE '%modo%'
    LOOP
        EXECUTE format('ALTER TABLE trabajo_ia DROP CONSTRAINT %I', restriccion);
    END LOOP;
END $$;
ALTER TABLE trabajo_ia ADD CONSTRAINT trabajo_ia_modo_check
    CHECK (modo IN ('RAPIDA', 'FINA', 'RECALIFICA', 'REBUSCA'));

-- ============================================================================
-- 6 · El agente que busca
-- ============================================================================
ALTER TABLE agente DROP CONSTRAINT agente_codigo_check;
ALTER TABLE agente ADD CONSTRAINT agente_codigo_check
    CHECK (codigo IN ('NECESIDAD_TALENTO', 'CAZATALENTOS', 'DATOS_CV', 'EVIDENCIA_CV',
                      'EVALUADOR', 'POTENCIAL_RIESGO', 'PRUEBA_PUESTO', 'SIMULACION',
                      'DESEMPENO', 'APRENDIZAJE', 'REDACTOR', 'EVALUADOR_TECNICO',
                      'RECOMENDADOR', 'BUSQUEDA_CV'));

